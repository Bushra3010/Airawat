// Writes supabase/seed.sql from lib/seed-data.ts. Run: npx tsx scripts/gen-seed.ts
// Compact on purpose (rows as arrays, image ids not URLs) so it fits in the SQL editor.
import { writeFileSync } from "node:fs";
import { categories, products, reviewsFor } from "../lib/seed-data";

const UNSPLASH = "https://images.unsplash.com/photo-";
const id = (url: string) => url.replace(UNSPLASH, "");
const REVIEWS = [
  ["Ananya R.", "Pune", "2026-10-12", 5, "Arrived a day early and the assembly team was in and out in forty minutes. The finish looks richer in person."],
  ["Karthik S.", "Chennai", "2026-09-28", 5, "Solid, no wobble, and the fabric has already survived a toddler and a juice box."],
  ["Meher P.", "Delhi", "2026-09-03", 4, "Colour is a shade darker than the photos, but honestly I like it more. Very comfortable."],
  ["Irfan K.", "Hyderabad", "2026-08-19", 5, "Third piece I've bought here. Consistent quality and the packaging was excellent."],
  ["Divya M.", "Bengaluru", "2026-08-02", 4, "Took a week longer than promised, but support kept me updated and the product is great."],
];
const offset = (slug: string) => REVIEWS.findIndex((r) => r[0] === reviewsFor(slug)[0].author);

const cats = categories.map((c) => [c.slug, c.name, c.room, c.blurb, id(c.image), c.subs]);
const prods = products.map((p) => [
  p.slug, p.category, p.name, p.sub, p.material, p.finish, p.colour, p.design, p.price, p.mrp, p.rating, p.ratingCount,
  p.shipsFast ? 1 : 0, p.deal ? 1 : 0, p.images.map(id), p.dims,
  p.variants.map((v) => [v.group, v.name, v.swatch, v.delta]), p.sizes.map((s) => [s.name, s.delta]), offset(p.slug),
]);
const json = JSON.stringify({ c: cats, p: prods, r: REVIEWS }).replace(/'/g, "''");

const sql = `-- Generated by scripts/gen-seed.ts. Re-runnable: replaces the catalogue (keeps products that have orders).
drop table if exists seed_json;
create temp table seed_json as select '${json}'::jsonb j;
delete from public.reviews; delete from public.product_sizes; delete from public.product_variants;
delete from public.products where id not in (select product_id from public.order_lines);
delete from public.categories where slug not in (select category_slug from public.products);

insert into public.categories (slug, name, room, blurb, image, subs, position)
select c->>0, c->>1, c->>2, c->>3, 'https://images.unsplash.com/photo-' || (c->>4),
       array(select jsonb_array_elements_text(c->5)), (o - 1)::int
from seed_json, jsonb_array_elements(j->'c') with ordinality as t(c, o)
on conflict (slug) do nothing;

insert into public.products (slug, category_slug, name, sub, material, finish, colour, design, price_paise, mrp_paise,
  rating, rating_count, ships_fast, deal, images, dims, summary, position)
select p->>0, p->>1, p->>2, p->>3, p->>4, p->>5, p->>6, p->>7, (p->>8)::int * 100, (p->>9)::int * 100,
  (p->>10)::numeric, (p->>11)::int, (p->>12) = '1', (p->>13) = '1',
  array(select 'https://images.unsplash.com/photo-' || x from jsonb_array_elements_text(p->14) x), p->>15,
  format('The %s is made in our own workshop from %s, finished by hand and checked twice before it leaves. %s lines, sturdy joinery and a finish that wears in, not out.',
         split_part(p->>2, ' ', 1), lower(p->>4), p->>7),
  (o - 1)::int
from seed_json, jsonb_array_elements(j->'p') with ordinality as t(p, o)
on conflict (slug) do nothing;

insert into public.product_variants (product_id, group_name, name, swatch, delta_paise, position)
select pr.id, v->>0, v->>1, v->>2, (v->>3)::int * 100, (vo - 1)::int
from seed_json, jsonb_array_elements(j->'p') p
join public.products pr on pr.slug = p->>0,
jsonb_array_elements(p->16) with ordinality as t(v, vo);

insert into public.product_sizes (product_id, name, delta_paise, position)
select pr.id, s->>0, (s->>1)::int * 100, (so - 1)::int
from seed_json, jsonb_array_elements(j->'p') p
join public.products pr on pr.slug = p->>0,
jsonb_array_elements(p->17) with ordinality as t(s, so);

insert into public.reviews (product_id, author, city, stars, body, created_at)
select pr.id, r->>0, r->>1, (r->>3)::smallint, r->>4, (r->>2)::date + time '12:00'
from seed_json, jsonb_array_elements(j->'p') p
join public.products pr on pr.slug = p->>0,
generate_series(0, 3) k,
lateral (select j->'r'->(((p->>18)::int + k) % 5) as r) rr;

drop table seed_json;

select (select count(*) from public.categories) categories, (select count(*) from public.products) products,
       (select count(*) from public.product_variants) variants, (select count(*) from public.product_sizes) sizes,
       (select count(*) from public.reviews) reviews;
`;
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log("wrote supabase/seed.sql", sql.length, "bytes; backticks:", (sql.match(/`|\$\{/g) || []).length);
